import ee from '../events/index.ts';
import { STATE } from '../core/state.ts';
const { Battle, Me } = STATE;

export function breakShield(name: string | number): string {
  return `TOUCH HAMMER ${name}`;
}

export function rageBreakShield(name: string | number): string {
  return `THROW CAUSTIC AT ${name}`;
}

/*
Miasma (a1)
Syntax:            THROW MIASMA AT <target>
Works on/against:  Denizens
Cooldown:          16.00 seconds
Resource:          14 rage
Details:
The toxic cloud generated by this chemical will choke the victim,
causing intense damage.
-------------------------------------------------------------------------------

Cadmium (a2)       (10 levels required)
Syntax:            EDUCE CADMIUM <TARGET>
Extra Information: Gives denizen affliction: Weakness
Works on/against:  Denizens
Cooldown:          31.00 seconds
Resource:          22 rage
Details:
Educing the symbol of cadmium will weaken your target for a short time,
decreasing the damage it can do. The symbol of cadmium is a bisected triangle.
-------------------------------------------------------------------------------

Caustic (a3)       (20 levels required)
Syntax:            THROW CAUSTIC AT <target>
Works on/against:  Denizens
Resource:          17 rage
Details:
The caustic is a very toxic chemical that can remove a denizen's shield.
-------------------------------------------------------------------------------

Magnesium (a4)     (35 levels required)
Syntax:            EDUCE MAGNESIUM <target>
Works on/against:  Denizens
Cooldown:          23.00 seconds
Resource:          36 rage
Details:
The counterpoint to iron, the symbol of this highly flammable metal will cause
your victim's limbs to burn with a white-hot flame.
The flames will last for a short time, causing intense damage to the target for their entire duration.
Symbol: A flare inscribed within a circle
-------------------------------------------------------------------------------

Pathogen (a5)      (50 levels required)
Syntax:            THROW PATHOGEN AT <target>
Extra Information: Uses denizen afflictions: Inhibit or Fear
Works on/against:  Denizens
Cooldown:          23.00 seconds
Resource:          25 rage
Details:
The pathogen is a virulent chemical that wreaks havoc on the internal organs of your victim,
doing increased damage against those who are unable to heal or are uncontrollably fearful.
-------------------------------------------------------------------------------

Hypnotic (a6)      (65 levels required)
Syntax:            THROW HYPNOTIC AT <target>
Extra Information: Gives denizen affliction: Amnesia
Works on/against:  Denizens
Cooldown:          41.00 seconds
Resource:          28 rage
Details:
The hypnotic is a potent chemical, the fumes of which cause your victim
to become extremely forgetful for a few seconds.
-------------------------------------------------------------------------------
*/
export function battleRage(rage: number, force = false): void {
  //
  // Miasma       A painful, choking cloud.
  // Cadmium      Weaken your enemy with cadmium.
  // Caustic      A chemical that burns through denizen shields.
  // Magnesium    Ignite your victim's limbs with white-hot flames.
  // Pathogen     A chemical that tears your victims apart from within.
  // Hypnotic     A chemical that dazes your victim into forgetfulness.
  //
  if (rage >= 14 && (force || Battle.bals.a1)) {
    setTimeout(() => (Battle.bals.a1 = true), 16_200);
    Battle.rage -= 14;
    Battle.bals.a1 = false;
    ee.emit('user:text', `THROW MIASMA AT ${Battle.tgtID}`);
    return;
  }

  if (rage >= 22 && (force || Battle.bals.a1)) {
    setTimeout(() => (Battle.bals.a1 = true), 31_200);
    Battle.rage -= 22;
    Battle.bals.a1 = false;
    ee.emit('user:text', 'EDUCE CADMIUM');
    return;
  }
}
